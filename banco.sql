
CREATE DATABASE IF NOT EXISTS empresa_vendas; 
USE empresa_vendas;
-- TABELA: categorias
CREATE TABLE categorias (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE
);

-- TABELA: clientes
CREATE TABLE clientes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado CHAR(2) NOT NULL,
    data_cadastro DATE NOT NULL
);

-- TABELA: vendedores
CREATE TABLE vendedores (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    setor VARCHAR(100) NOT NULL,
    contato VARCHAR(20) UNIQUE
);

-- TABELA: produtos
CREATE TABLE produtos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome_produto VARCHAR(150) NOT NULL,
    categoria_id INT NOT NULL,
    preco DECIMAL(10,2) NOT NULL,
    custo DECIMAL(10,2) NOT NULL,
    estoque INT NOT NULL DEFAULT 0,
    marca VARCHAR(80) NOT NULL,
    FOREIGN KEY (categoria_id) REFERENCES categorias(id),
    CHECK (preco >= 0),
    CHECK (custo >= 0),
    CHECK (estoque >= 0)
);

-- TABELA: pedidos
CREATE TABLE pedidos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cliente_id INT NOT NULL,
    vendedor_id INT NOT NULL,
    data_pedido DATE NOT NULL,
    status ENUM('PENDENTE','PROCESSANDO','CONCLUIDO','CANCELADO') NOT NULL DEFAULT 'PENDENTE',
	FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    FOREIGN KEY (vendedor_id) REFERENCES vendedores(id)
) ;

-- TABELA: itens_pedido
CREATE TABLE itens_pedido (
    id INT AUTO_INCREMENT PRIMARY KEY,
    pedido_id INT NOT NULL,
    produto_id INT NOT NULL,
    quantidade INT NOT NULL,
    preco_unitario DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (pedido_id) REFERENCES pedidos(id),
    FOREIGN KEY (produto_id) REFERENCES produtos(id),
        CHECK (quantidade > 0),
        CHECK (preco_unitario >= 0)
);

-- TABELA: pagamentos
CREATE TABLE pagamentos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    pedido_id INT NOT NULL,
    forma_pagamento ENUM('PIX','CARTAO_CREDITO','CARTAO_DEBITO','BOLETO') NOT NULL,
    valor DECIMAL(10,2) NOT NULL,
    status ENUM('PAGO','PENDENTE','ESTORNADO') NOT NULL DEFAULT 'PENDENTE',
    data_pagamento DATE,
    FOREIGN KEY (pedido_id) REFERENCES pedidos(id),
        CHECK (valor >= 0)
) ;


